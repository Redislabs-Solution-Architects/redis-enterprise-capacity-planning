"""REQ-06 placement and REQ-05 create regressions."""
import json
from pathlib import Path
import pytest
from hypothesis import given, strategies as st, settings

G=2**30
FIXTURES=Path(__file__).parent/'fixtures'


def fixture():
    return json.loads((FIXTURES/'no-rack.json').read_text())


@pytest.mark.skipif(not (FIXTURES/'poc-parity.json').exists(),reason='P-1 generated by T12')
def test_req06_poc_parity():
    """Given: `tests/fixtures/poc-5-nodes.json`
    When: each `CANCREATE` case recorded in P-1 is replayed as `recap can-create`
    Then: the verdict equals the POC verdict, or the case carries a `divergence_reason` from P-1.
    """
    from recap.planner.create import plan
    data=json.loads((FIXTURES/'poc-parity.json').read_text())
    for case in data['cases']:
        if case['command']=='can-create':
            actual=plan(json.loads((FIXTURES/'poc-5-nodes.json').read_text()),**case['args'])
            assert actual['verdict']==case['verdict'] or case.get('divergence_reason')


def test_req06_not_enough_ram():
    """Given: 2 nodes on 2 racks, each with `free_ram` of exactly 5 GiB
    When: `recap can-create --memory 20GiB --shards 2 --replication` (4 shards of 5 GiB)
    Then: exit 1, with reason `ram`.
    """
    from recap.planner.create import plan
    s=fixture()
    s['nodes']=s['nodes'][:2]
    for n in s['nodes']: n.update(provisional_ram=5*G,rack_id=str(n['uid']))
    s['bdbs']=[];s['shards']=[]
    result=plan(s,20*G,2,replication=True)
    assert result['verdict']=='infeasible' and result['reasons'][0].startswith('ram')


def test_req05_four_rack_regression():
    """Given: a rack-aware cluster with 4 racks. Rack A has two nodes with 15 GiB `free_ram` each; racks B, C and D have one node each with 5 GiB.
    When: `recap can-create --memory 40GiB --shards 4 --replication` (8 shards of 5 GiB)
    Then: exit 1, with a reason that starts `rack-awareness:`.
    """
    from recap.planner.create import plan
    s=fixture(); base=s['nodes'][0]
    s['bdbs']=[];s['shards']=[]
    s['cluster']['rack_aware']=True
    s['nodes']=[dict(base,uid=i+1,rack_id=rack,provisional_ram=ram*G,shard_count=0) for i,(rack,ram) in enumerate([('A',15),('A',15),('B',5),('C',5),('D',5)])]
    result=plan(s,40*G,4,replication=True)
    assert result['verdict']=='infeasible'
    assert result['reasons'][0].startswith('rack-awareness:')


def test_req05_no_replication_no_rack_rule():
    """Given: a cluster with `rack_aware == false` and no rack ids
    When: `recap can-create --memory 10GiB --shards 1` (no replication)
    Then: JSON `reasons[]` contains no `rack-awareness` entry (F-6).
    """
    from recap.planner.create import plan
    result=plan(fixture(),10*G,1)
    assert not any('rack-awareness' in r for r in result['reasons'])


@given(st.lists(st.integers(0,8),min_size=2,max_size=5),st.integers(1,4),st.booleans())
@settings(max_examples=40,deadline=None)
def test_req05_property_all_create_intermediate_states(rams,count,replication):
    from recap.planner.create import plan
    from recap.verifier import verify
    from recap.constraints import violations
    s=fixture();base=s['nodes'][0]
    s['bdbs']=[];s['shards']=[]
    s['nodes']=[dict(base,uid=i+1,rack_id=str(i%3),provisional_ram=ram*G,shard_count=0) for i,ram in enumerate(rams)]
    result=plan(s,count*G*(2 if replication else 1),count,replication=replication,rack_aware=True)
    if result['verdict']=='feasible':
        state=verify(s,result['plan'],result['goal'])
        assert violations(state)==[]
