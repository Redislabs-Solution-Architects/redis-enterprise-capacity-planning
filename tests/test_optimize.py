"""REQ-08 heuristic and safety scenarios."""
from argparse import Namespace
import json
from pathlib import Path
import pytest
from hypothesis import given, strategies as st, settings

FIXTURES=Path(__file__).parent/'fixtures'


def args(scope='cluster',**kw):
    return Namespace(scope=scope,node=None,db=None,rack=None,shard_size_min=None,shard_size_max=None,
                     shard_used_max='policy',level=1,need=None,reserve_shard_size=None,explain=False,**kw)


def run(name,scope='cluster',**kw):
    from recap.planner.optimize import plan
    options=args(scope)
    for key,value in kw.items(): setattr(options,key,value)
    return plan(json.loads((FIXTURES/f'{name}.json').read_text()),options)


@pytest.mark.skipif(not (FIXTURES/'poc-parity.json').exists(),reason='P-1 generated by T12')
def test_req08_poc_parity():
    """Given: `tests/fixtures/poc-5-nodes.json`
    When: each `O N` case recorded in P-1 is replayed as `recap optimize node`
    Then: every emitted step moves a replica; every intermediate state passes `violations()`; and the move list equals the POC's, or the case carries a `divergence_reason` (expected: F-13).
    """
    from recap.verifier import verify
    snapshot=json.loads((FIXTURES/'poc-5-nodes.json').read_text())
    for case in json.loads((FIXTURES/'poc-parity.json').read_text())['cases']:
        if case['command']=='optimize':
            result=run('poc-5-nodes','node',**case['args'])
            verify(snapshot,result['plan'])
            moves=[(s['shard_uid'],s['from_node'],s['to_node']) for s in result['plan']]
            assert moves==[tuple(x) for x in case['moves']] or case.get('divergence_reason')


def test_req08_densify_decrements_target():
    """Given: `tests/fixtures/densify.json`. The densify target has 2.5 GiB `free_ram` and free slots; 5 replicas of 1 GiB exist on other nodes, and their masters are on other racks.
    When: `recap optimize cluster`
    Then: exit 0, verdict `goal-met`, and exactly 2 migrations target that node (F-4 regression).
    """
    result=run('densify')
    assert result['verdict']=='goal-met'
    assert len(result['plan'])==2
    assert all(s['to_node']==1 for s in result['plan'])


def test_req08_no_rack():
    """Given: `tests/fixtures/no-rack.json`: 3 nodes with no rack ids. Node 1 hosts a 1 GiB replica whose master is on node 3, and node 2 has 10 GiB `free_ram`.
    When: `recap optimize node --node 1`
    Then: exit 0, and `plan[]` has at least 1 step (F-7 regression).
    """
    result=run('no-rack','node',node='1')
    assert result['verdict']=='goal-met' and result['plan']


def test_req08_db_excludes_own_shards():
    """Given: `tests/fixtures/poc-5-nodes.json`
    When: `recap optimize db --db 1`
    Then: no step moves a shard of database 1.
    """
    s=json.loads((FIXTURES/'poc-5-nodes.json').read_text())
    own={x['uid'] for x in s['shards'] if x['bdb_uid']==1}
    assert all(step['shard_uid'] not in own for step in run('poc-5-nodes','db',db='1')['plan'])


@given(st.integers(0,10))
@settings(max_examples=11,deadline=None)
def test_req05_property_optimize_states(target_gib):
    from recap.planner.optimize import plan
    from recap.verifier import verify
    from recap.constraints import violations
    s=json.loads((FIXTURES/'no-rack.json').read_text())
    s['nodes'][1]['provisional_ram']=target_gib*2**30
    options=args('node');options.node='1'
    result=plan(s,options)
    final=verify(s,result['plan'],result.get('goal') if result['verdict']=='goal-met' else None)
    assert violations(final)==[]


